function formatTime(isoString) {
  const d = new Date(isoString);
  const timeStr = d.toLocaleTimeString([], {
    hour: '2-digit',
    minute: '2-digit',
  });
  const now = new Date();
  const startOfToday = new Date(
    now.getFullYear(),
    now.getMonth(),
    now.getDate(),
  );
  const startOfYesterday = new Date(startOfToday - 86400000);
  const startOfEntry = new Date(d.getFullYear(), d.getMonth(), d.getDate());

  let dateStr;
  if (startOfEntry.getTime() === startOfToday.getTime()) {
    dateStr = 'Today';
  } else if (startOfEntry.getTime() === startOfYesterday.getTime()) {
    dateStr = 'Yesterday';
  } else {
    dateStr = d.toLocaleDateString([], {
      day: 'numeric',
      month: 'short',
      year: 'numeric',
    });
  }

  return `${dateStr} at ${timeStr}`;
}

function formatElapsed(ms, includeAgo = true) {
  const suffix = includeAgo ? ' ago' : '';
  const totalMins = Math.floor(ms / 60000);
  if (totalMins < 1) return 'Just now';
  if (totalMins < 60) return `${totalMins}m${suffix}`;
  const hours = Math.floor(totalMins / 60);
  const mins = totalMins % 60;
  if (hours < 24)
    return mins > 0 ? `${hours}h ${mins}m${suffix}` : `${hours}h${suffix}`;
  const days = Math.floor(hours / 24);
  const remHours = hours % 24;
  return remHours > 0
    ? `${days}d ${remHours}h${suffix}`
    : `${days}d${suffix}`;
}

function formatDuration(ms) {
  const totalMins = Math.round(ms / 60000);
  if (!Number.isFinite(totalMins) || totalMins <= 0) return '—';
  if (totalMins < 60) return `${totalMins}m`;
  const hours = Math.floor(totalMins / 60);
  const mins = totalMins % 60;
  if (hours < 24) return mins > 0 ? `${hours}h ${mins}m` : `${hours}h`;
  const days = Math.floor(hours / 24);
  const remHours = hours % 24;
  return remHours > 0 ? `${days}d ${remHours}h` : `${days}d`;
}

