async function saveEntry() {
  const tsInput = document.getElementById('timestamp-input').value;
  const timestamp = tsInput ? new Date(tsInput).toISOString() : nowIso();
  const stamp = nowIso();
  let savedEntries;

  if (formState.type === 'medication') {
    savedEntries = selectedMedicationDoses().map(({ medication, amount }) => {
      const med = findMed(medication);
      return {
        id: uid('entry_'),
        timestamp,
        user: formState.user,
        baby: formState.baby,
        type: 'medication',
        amount: parseFloat(amount),
        unit: med?.unit || 'ml',
        medication,
        createdAt: stamp,
        updatedAt: stamp,
        deletedAt: null,
      };
    });
  } else {
    savedEntries = [
      {
        id: uid('entry_'),
        timestamp,
        user: formState.user,
        baby: formState.type === 'express' ? null : formState.baby,
        type: formState.type,
        ...(formState.type !== 'poo' && {
          amount: parseFloat(formState.amount),
          unit: currentUnit(),
        }),
        medication: formState.medication,
        createdAt: stamp,
        updatedAt: stamp,
        deletedAt: null,
      },
    ];
  }
  if (!savedEntries.length) return;

  await mutateData((next) => {
    next.entries.unshift(...savedEntries);
  });

  const baby = findBaby(formState.baby);
  const user = findUser(formState.user);
  let detail;
  let amountStr = '';
  if (formState.type === 'medication') {
    detail = savedEntries
      .map((entry) => {
        const med = findMed(entry.medication);
        return `${med?.label || entry.medication} ${entry.amount} ${
          entry.unit
        }`;
      })
      .join(' + ');
  } else {
    const entry = savedEntries[0];
    detail =
      formState.type === 'poo'
        ? 'Poo'
        : formState.type === 'weight'
          ? 'Weight'
          : formState.type === 'express'
            ? 'Expressed'
            : 'Milk';
    amountStr =
      formState.type === 'weight'
        ? ` ${formatWeightLbOz(weightGrams(entry))}`
        : formState.type !== 'poo'
          ? ` ${entry.amount} ${entry.unit}`
          : '';
  }
  const conf = document.getElementById('confirmation');
  const subject =
    formState.type === 'express'
      ? user?.name || formState.user
      : baby?.name || formState.baby;
  conf.textContent = `Saved - ${subject}: ${detail}${amountStr}`;
  conf.classList.remove('hidden');
  setTimeout(() => conf.classList.add('hidden'), 3000);

  formState.type = null;
  resetMedicationSelection();
  formState.amount = '';
  renderTypeButtons();
  document.getElementById('step-medication').classList.add('hidden');
  document.getElementById('amount-group').classList.add('hidden');
  document.getElementById('weight-group').classList.add('hidden');
  document.getElementById('amount-input').value = '';
  resetWeightInputs();
  document.getElementById('timestamp-input').value = '';
  document.getElementById('timestamp-input').classList.add('hidden');
  document.getElementById('timestamp-toggle').classList.remove('active');
  updateUnitLabel();
  updateSaveBtn();
}

