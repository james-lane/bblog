function weightTrendByBaby(activeBabies) {
  const babyMap = new Map(activeBabies.map((baby) => [baby.id, baby]));
  const byBaby = Object.fromEntries(activeBabies.map((baby) => [baby.id, []]));
  for (const e of entries()) {
    const baby = babyMap.get(e.baby);
    if (e.type !== 'weight' || !baby) continue;
    const grams = weightGrams(e);
    const timestamp = new Date(e.timestamp).getTime();
    if (!grams || !Number.isFinite(timestamp)) continue;
    const baseline = babyGrowthChartBaseline(baby);
    byBaby[e.baby].push({
      timestamp,
      grams,
      ageMonths: ageMonthsAt(timestamp, baseline?.date),
      ageEstimated: false,
      ageBaseline: baseline?.type || null,
    });
  }
  for (const baby of activeBabies) {
    const points = byBaby[baby.id] || [];
    points.sort((a, b) => a.timestamp - b.timestamp);
    if (babyGrowthChartBaseline(baby) || !points.length) continue;
    const baselineTimestamp = points[0].timestamp;
    points.forEach((point) => {
      point.ageMonths = ageMonthsBetween(point.timestamp, baselineTimestamp);
      point.ageEstimated = true;
      point.ageBaseline = 'firstWeight';
    });
  }
  return byBaby;
}

function milkLiveStats(now = Date.now()) {
  const windowStart = now - 86400000;
  const stats = {};

  for (const e of entries()) {
    if (e.type !== 'milk' || !e.baby) continue;
    const t = new Date(e.timestamp).getTime();
    if (!Number.isFinite(t) || t > now) continue;

    if (!stats[e.baby]) {
      stats[e.baby] = {
        lastAt: null,
        lastAmount: null,
        previousAt: null,
        previousAmount: null,
        rollingAmount: 0,
        rollingFeeds: 0,
      };
    }

    const amount = milkAmount(e);
    if (amount <= 0) continue;

    if (stats[e.baby].lastAt == null || t > stats[e.baby].lastAt) {
      stats[e.baby].previousAt = stats[e.baby].lastAt;
      stats[e.baby].previousAmount = stats[e.baby].lastAmount;
      stats[e.baby].lastAt = t;
      stats[e.baby].lastAmount = amount;
    } else if (
      stats[e.baby].previousAt == null ||
      t > stats[e.baby].previousAt
    ) {
      stats[e.baby].previousAt = t;
      stats[e.baby].previousAmount = amount;
    }

    if (t >= windowStart) {
      stats[e.baby].rollingAmount += amount;
      stats[e.baby].rollingFeeds += 1;
    }
  }

  return stats;
}

