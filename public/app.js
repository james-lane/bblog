function renderCharts() {
  const chartContent = document.getElementById('charts-content');
  const pagination = document.getElementById('charts-pagination');
  if (!chartContent || !pagination) return;
  const title = document.getElementById('charts-card-title');
  const summary = document.getElementById('charts-card-summary');
  const paginationScrollLeft = pagination.scrollLeft;
  pagination.innerHTML = CHART_PAGES.map(
    (page) => `
    <button id="charts-page-${escapeHtml(page.id)}" class="charts-page-pill" type="button" role="tab" aria-controls="charts-content" aria-selected="${page.id === _activeChartPage}" tabindex="${page.id === _activeChartPage ? '0' : '-1'}" data-chart-page="${escapeHtml(page.id)}">
      ${escapeHtml(page.name)}
    </button>`,
  ).join('');
  pagination.scrollLeft = paginationScrollLeft;
  chartContent.setAttribute(
    'aria-labelledby',
    `charts-page-${_activeChartPage}`,
  );

  const activeBabies = babies();
  if (_activeChartPage === 'milk') {
    destroyWeightTrendChart();
    destroyExpressingChart();
    if (title) title.textContent = 'Milk intake';
    if (summary) summary.textContent = selectedMilkStatsRangeBounds().summary;
    if (!activeBabies.length) {
      destroyMilkIntakeChart();
      chartContent.innerHTML =
        '<p class="log-empty" style="padding:40px 0">No babies configured.</p>';
      return;
    }

    chartContent.innerHTML = renderMilkIntakeTrend(activeBabies);
    initMilkIntakeChart(activeBabies);
    return;
  }

  if (_activeChartPage === 'express') {
    destroyWeightTrendChart();
    destroyMilkIntakeChart();
    if (title) title.textContent = 'Expressing';
    if (summary)
      summary.textContent = selectedExpressStatsRangeBounds().summary;
    const activeParents = expressingParents();
    if (!activeParents.length) {
      destroyExpressingChart();
      chartContent.innerHTML =
        '<p class="log-empty" style="padding:40px 0">Enable expressing for a parent in Settings to begin tracking.</p>';
      return;
    }

    chartContent.innerHTML = renderExpressingTrend(activeParents);
    initExpressingChart(activeParents);
    return;
  }

  destroyMilkIntakeChart();
  destroyExpressingChart();
  if (title) title.textContent = 'Weight trend';
  if (summary) summary.textContent = growthSettingSummary();
  chartContent.innerHTML =
    '<div id="charts-weight-chart" class="dash-weight-chart"></div>';
  const weightChart = document.getElementById('charts-weight-chart');
  if (!activeBabies.length) {
    destroyWeightTrendChart();
    weightChart.innerHTML =
      '<p class="log-empty" style="padding:40px 0">No babies configured.</p>';
    return;
  }

  weightChart.innerHTML = renderWeightTrend(activeBabies);
  initWeightTrendChart(activeBabies);
  wireWeightZoomControls();
}

function refreshDashboardLiveTimes() {
  if (
    !data ||
    !document.getElementById('tab-dashboard')?.classList.contains('active')
  )
    return;
  const now = Date.now();
  const liveStats = milkLiveStats(now);
  document
    .querySelectorAll('.dash-live-metric[data-live-baby-id]')
    .forEach((metric) => {
      const babyId = metric.dataset.liveBabyId;
      const stats = liveStats[babyId];
      const lastFeed =
        stats?.lastAt != null
          ? formatElapsed(now - stats.lastAt, false)
          : 'No feed yet';
      const valueEl = metric.querySelector('.dash-live-last-value');
      const amountEl = metric.querySelector('.dash-live-last-amount');
      if (valueEl) valueEl.textContent = lastFeed;
      if (amountEl) {
        amountEl.textContent =
          stats?.lastAt != null ? formatMilkAmount(stats.lastAmount) : '';
        amountEl.hidden = stats?.lastAt == null;
      }
      const medicationEl = metric.querySelector('[data-medication-baby-id]');
      const baby = findBaby(babyId);
      if (medicationEl && baby) {
        const medicationRows = renderDashboardMedicationRows(baby, now);
        medicationEl.innerHTML = medicationRows;
        medicationEl.classList.toggle('hidden', !medicationRows);
      }
    });
}

function nextDashboardClockDelay(now = Date.now()) {
  let nextDelay = 60000;
  const liveStats = milkLiveStats(now);

  for (const stat of Object.values(liveStats)) {
    if (stat?.lastAt == null) continue;
    const elapsed = Math.max(0, now - stat.lastAt);
    const delay = elapsed < 60000 ? 60000 - elapsed : 60000 - (elapsed % 60000);
    nextDelay = Math.min(nextDelay, delay);
  }

  return Math.max(1000, Math.ceil(nextDelay) + 50);
}

function scheduleDashboardClockRefresh() {
  clearTimeout(dashboardClockTimer);
  if (
    !data ||
    !document.getElementById('tab-dashboard')?.classList.contains('active')
  )
    return;
  dashboardClockTimer = setTimeout(() => {
    refreshDashboardLiveTimes();
    scheduleDashboardClockRefresh();
  }, nextDashboardClockDelay());
}

