function milkIntakeStats(start, end, activeBabies) {
  const stats = {};
  activeBabies.forEach((baby) => {
    stats[baby.id] = {
      total: 0,
      feeds: 0,
      feedTimes: [],
    };
  });

  for (const e of entries()) {
    const stat = stats[e.baby];
    if (e.type !== 'milk' || !stat) continue;
    const t = new Date(e.timestamp).getTime();
    if (!Number.isFinite(t) || t < start || t >= end) continue;
    const amount = milkAmount(e);
    if (amount <= 0) continue;

    stat.total += amount;
    stat.feeds += 1;
    stat.feedTimes.push(t);
  }

  Object.values(stats).forEach((stat) => {
    stat.avgFeed = stat.feeds ? stat.total / stat.feeds : null;
    stat.feedTimes.sort((a, b) => a - b);
    let totalGapMs = 0;
    for (let i = 1; i < stat.feedTimes.length; i += 1) {
      totalGapMs += stat.feedTimes[i] - stat.feedTimes[i - 1];
    }
    stat.avgGapMs =
      stat.feedTimes.length > 1
        ? totalGapMs / (stat.feedTimes.length - 1)
        : null;
  });

  return stats;
}

function expressingStats(start, end, activeParents) {
  const stats = {};
  activeParents.forEach((parent) => {
    stats[parent.id] = {
      total: 0,
      sessions: 0,
    };
  });

  for (const entry of entries()) {
    const stat = stats[entry.user];
    if (entry.type !== 'express' || !stat) continue;
    const timestamp = new Date(entry.timestamp).getTime();
    if (
      !Number.isFinite(timestamp) ||
      timestamp < start ||
      timestamp >= end
    )
      continue;
    const amount = milkAmount(entry);
    if (amount <= 0) continue;

    stat.total += amount;
    stat.sessions += 1;
  }

  Object.values(stats).forEach((stat) => {
    stat.avgSession = stat.sessions ? stat.total / stat.sessions : null;
  });

  return stats;
}

