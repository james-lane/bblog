function normalizeRecordList(records, mapper) {
  return (Array.isArray(records) ? records : [])
    .filter((item) => item && item.id)
    .map((item) => {
      const stamp =
        item.updatedAt || item.createdAt || item.timestamp || nowIso();
      return mapper(stamped(item, stamp));
    });
}

function normalizeDateOnly(value) {
  const match = String(value || '')
    .trim()
    .match(/^(\d{4})-(\d{2})-(\d{2})/);
  if (!match) return null;
  const year = Number(match[1]);
  const month = Number(match[2]);
  const day = Number(match[3]);
  const date = new Date(Date.UTC(year, month - 1, day));
  if (
    date.getUTCFullYear() !== year ||
    date.getUTCMonth() !== month - 1 ||
    date.getUTCDate() !== day
  )
    return null;
  return `${String(year).padStart(4, '0')}-${String(month).padStart(2, '0')}-${String(day).padStart(2, '0')}`;
}

function dateOnlyUtcMs(value) {
  const normalized = normalizeDateOnly(value);
  if (!normalized) return null;
  const [year, month, day] = normalized.split('-').map(Number);
  return Date.UTC(year, month - 1, day);
}

function normalizeTimestamp(value) {
  const time = new Date(value || '').getTime();
  return Number.isFinite(time) ? new Date(time).toISOString() : null;
}

function normalizeData(value) {
  const stamp = nowIso();
  const source = value && typeof value === 'object' ? value : {};
  const normalizedBabies = normalizeRecordList(source.babies, (item) => {
    const birthDate = normalizeDateOnly(
      item.birthDate || item.dateOfBirth || item.dob,
    );
    const dueDate = normalizeDateOnly(
      item.dueDate || item.estimatedDueDate || item.edd,
    );
    return {
      id: item.id,
      name: String(item.name || item.label || '').trim() || 'Baby',
      birthDate,
      dueDate,
      birthDateUpdatedAt:
        normalizeTimestamp(item.birthDateUpdatedAt) ||
        (birthDate ? item.updatedAt : null),
      dueDateUpdatedAt:
        normalizeTimestamp(item.dueDateUpdatedAt) ||
        (dueDate ? item.updatedAt : null),
      createdAt: item.createdAt,
      updatedAt: item.updatedAt,
      deletedAt: item.deletedAt || null,
    };
  });
  const legacyMedicationBabyIds = normalizedBabies
    .filter((baby) => !baby.deletedAt)
    .map((baby) => baby.id);
  const result = {
    schemaVersion: 1,
    meta: {
      createdAt: source.meta?.createdAt || stamp,
      updatedAt: source.meta?.updatedAt || stamp,
    },
    users: normalizeRecordList(source.users, (item) => ({
      id: item.id,
      name: String(item.name || item.label || '').trim() || 'Parent',
      canExpress: item.canExpress === true,
      createdAt: item.createdAt,
      updatedAt: item.updatedAt,
      deletedAt: item.deletedAt || null,
    })),
    babies: normalizedBabies,
    medications: normalizeRecordList(source.medications, (item) => ({
      id: item.id,
      label: String(item.label || item.name || '').trim() || 'Medication',
      unit: String(item.unit || 'ml').trim() || 'ml',
      babyIds: Array.isArray(item.babyIds)
        ? [...new Set(item.babyIds.map(String).filter(Boolean))]
        : legacyMedicationBabyIds,
      ...(item.defaultAmount != null && item.defaultAmount !== ''
        ? { defaultAmount: Number(item.defaultAmount) }
        : {}),
      ...(item.intervalHours != null && item.intervalHours !== ''
        ? { intervalHours: Number(item.intervalHours) }
        : {}),
      createdAt: item.createdAt,
      updatedAt: item.updatedAt,
      deletedAt: item.deletedAt || null,
    })),
    entries: normalizeRecordList(source.entries, (item) => ({
      id: item.id,
      timestamp: item.timestamp || item.createdAt || stamp,
      user: item.user || null,
      baby: item.baby || null,
      type: item.type || 'milk',
      ...(item.amount != null && item.amount !== ''
        ? { amount: Number(item.amount) }
        : {}),
      ...(item.unit ? { unit: item.unit } : {}),
      medication: item.medication || null,
      createdAt: item.createdAt || item.timestamp || stamp,
      updatedAt: item.updatedAt,
      deletedAt: item.deletedAt || null,
    })),
  };

  result.users.sort(sortByCreatedThenName);
  result.babies.sort(sortByCreatedThenName);
  result.medications.sort(sortByCreatedThenName);
  result.entries.sort((a, b) => new Date(b.timestamp) - new Date(a.timestamp));
  return result;
}

