function weightTrendModel(activeBabies) {
  const seriesByBaby = weightTrendByBaby(activeBabies);
  const loggedSeries = activeBabies
    .map((baby) => ({ baby, points: seriesByBaby[baby.id] || [] }))
    .filter(({ points }) => points.length);
  let missingAgeCount = 0;
  let estimatedAgeCount = 0;
  let beforeRangeCount = 0;
  let afterRangeCount = 0;
  const series = loggedSeries
    .map(({ baby, points }) => {
      const plottable = points.filter((point) => {
        if (!Number.isFinite(point.ageMonths)) {
          missingAgeCount += 1;
          return false;
        }
        if (point.ageMonths < 0) {
          beforeRangeCount += 1;
          return false;
        }
        if (point.ageMonths > 24) {
          afterRangeCount += 1;
          return false;
        }
        if (point.ageEstimated) estimatedAgeCount += 1;
        return true;
      });
      return { baby, points: plottable };
    })
    .filter(({ points }) => points.length);
  const allPoints = series.flatMap(({ points }) => points);

  const totalWeights = loggedSeries.reduce(
    (sum, item) => sum + item.points.length,
    0,
  );
  return {
    loggedSeries,
    series,
    allPoints,
    totalWeights,
    missingAgeCount,
    estimatedAgeCount,
    beforeRangeCount,
    afterRangeCount,
  };
}

